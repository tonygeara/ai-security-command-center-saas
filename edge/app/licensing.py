"""Offline (on-prem) licensing.

A license is a small JSON file signed with the vendor's Ed25519 private key, which never
leaves the vendor's PC. The app only holds the public key below, so it can check a
license but cannot create or alter one. Each license is locked to one laptop's machine
ID and has an expiry date, a plan, feature switches and camera/drone limits.

License file format (license.lic):
    {"license": {...payload...}, "signature": "<base64 Ed25519 signature>"}
"""
import base64
import datetime
import hashlib
import json
import os
import time

# Vendor public key (Ed25519, raw 32 bytes, base64). Generated by tools/license_tool.py.
PUBLIC_KEY_B64 = "FdDMvjooLB3N8bOWc6mjnX1AjPcZHcQ8B5da/E01Lb4="

FEATURES = ("camera_ai", "face_ai", "lpr", "drone_live", "drone_ai", "drone_tracking", "drone_control")
# Flying the drone from the laptop is only licensed when asked for explicitly.
OPT_IN_FEATURES = ("drone_control",)


def machine_id():
    """Stable ID for this Windows installation, shown to the customer and put in the license.
    Derived from the Windows MachineGuid (hashed, so the raw GUID is never shared)."""
    raw = ""
    try:
        import winreg
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\Microsoft\Cryptography",
                            0, winreg.KEY_READ | getattr(winreg, "KEY_WOW64_64KEY", 0)) as key:
            raw = str(winreg.QueryValueEx(key, "MachineGuid")[0])
    except Exception:
        import uuid
        raw = "node-%012x" % uuid.getnode()
    digest = hashlib.sha256(("ai-command-centre:" + raw.strip().lower()).encode("utf-8")).hexdigest().upper()
    return "-".join(digest[i:i + 4] for i in range(0, 20, 4))


def canonical(payload):
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def _public_key():
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    return Ed25519PublicKey.from_public_bytes(base64.b64decode(PUBLIC_KEY_B64))


def verify(document, machine=None, now=None):
    """Check a license document. Returns (ok, reason, payload)."""
    if not isinstance(document, dict):
        return False, "Not a license file.", None
    payload = document.get("license")
    signature = document.get("signature")
    if not isinstance(payload, dict) or not signature:
        return False, "Not a license file.", None
    try:
        _public_key().verify(base64.b64decode(signature), canonical(payload))
    except Exception:
        return False, "License signature is invalid (the file was changed or not issued by the vendor).", payload
    if str(payload.get("machine_id", "")).upper() != str(machine or machine_id()).upper():
        return False, "This license belongs to a different computer.", payload
    expires = str(payload.get("expires") or "")
    if expires:
        try:
            end = datetime.date.fromisoformat(expires)
        except ValueError:
            return False, "License expiry date is invalid.", payload
        today = datetime.date.fromtimestamp(now or time.time())
        if today > end:
            return False, f"License expired on {expires}.", payload
    return True, "Valid", payload


def load(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def check_file(path, machine=None, now=None):
    """Verify the license file at `path`. Returns (ok, reason, payload)."""
    if not os.path.isfile(path):
        return False, "No license installed.", None
    try:
        return verify(load(path), machine=machine, now=now)
    except Exception as e:
        return False, f"License file could not be read: {e}", None


def features_for_dashboard(payload):
    """Translate a license payload into the entitlement shape the dashboard already uses."""
    enabled = set(payload.get("features") or [])
    limits = payload.get("limits") or {}
    features = {k: {"enabled": k in enabled, "limit_value": None} for k in FEATURES}
    if "cameras" in limits:
        features["camera_ai"]["limit_value"] = limits.get("cameras")
    if "drones" in limits:
        features["drone_live"]["limit_value"] = limits.get("drones")
    return features


def sign(payload, private_key):
    """Vendor side: produce a license document (used by tools/license_tool.py)."""
    return {"license": payload, "signature": base64.b64encode(private_key.sign(canonical(payload))).decode("ascii")}
