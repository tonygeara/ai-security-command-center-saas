# Builds "AI Command Centre Lebanon": the on-prem edition with offline licensing and
# compiled (native) application code, plus a USB package for laptops without internet.
#   powershell -ExecutionPolicy Bypass -File edge\installer\build_onprem.ps1 [-SkipImages]
# Output: edge\installer\output\onprem-usb\
#   AI-Command-Centre-Lebanon-Setup-<version>.exe
#   ai-command-centre-images.tar      (AI services, so the first start needs no internet)
#   INSTALL.txt
param([switch]$SkipImages)
$ErrorActionPreference = 'Stop'
$Installer = $PSScriptRoot
$Edge = Split-Path -Parent $Installer
$App = Join-Path $Edge 'app'
$Venv = Join-Path $Edge '.venv-onprem'
$Stage = Join-Path $Installer 'build\onprem-stage'
$Usb = Join-Path $Installer 'output\onprem-usb'
$Name = 'AI Command Centre Lebanon'
$Slug = 'AI-Command-Centre-Lebanon'
$AppId = '{6F3C2A9E-5B1D-4E8A-9C47-2D8B1F0A7E53}'
$env:NUITKA_CACHE_DIR = Join-Path $Installer 'build\nuitka-cache'

$version = (Select-String -Path (Join-Path $App 'launcher.pyw') -Pattern "^APP_VERSION = '(.+)'").Matches[0].Groups[1].Value
Write-Host "Building $Name $version (on-prem)" -ForegroundColor Cyan

# Python 3.12 environment (Nuitka's bundled compiler supports 3.12).
if (-not (Test-Path (Join-Path $Venv 'Scripts\python.exe'))) {
    $py312 = Join-Path $env:LOCALAPPDATA 'Programs\Python\Python312\python.exe'
    if (-not (Test-Path $py312)) { throw 'Python 3.12 is required: winget install -e --id Python.Python.3.12' }
    & $py312 -m venv $Venv
}
$python = Join-Path $Venv 'Scripts\python.exe'
& $python -m pip install --quiet -r (Join-Path $Edge 'requirements.txt') 'pyinstaller>=6.10,<7' 'nuitka>=2.5,<3' ordered-set zstandard
if ($LASTEXITCODE) { throw 'Dependency install failed' }

# Licenses only verify against the public key embedded in licensing.py.
if ((Get-Content (Join-Path $App 'licensing.py') -Raw) -match '__PUBLIC_KEY__') {
    throw 'No license signing key yet: run  python edge\tools\license_tool.py init'
}

# 1. Staging folder: on-prem edition settings + sources to compile.
if (Test-Path $Stage) { Remove-Item $Stage -Recurse -Force }
New-Item -ItemType Directory -Force $Stage | Out-Null
Copy-Item (Join-Path $App 'launcher.pyw') $Stage
Copy-Item (Join-Path $App 'dashboard.py') $Stage
Copy-Item (Join-Path $App 'licensing.py') $Stage
@"
# On-prem edition (generated by build_onprem.ps1).
EDITION = "onprem"
PRODUCT_NAME = "$Name"
BRAND_TOP = "AI COMMAND CENTRE"
BRAND_SUB = "LEBANON"
BRAND_FLAG = "lb"
DATA_DIR_NAME = "$Slug"
"@ | Set-Content (Join-Path $Stage 'edition.py') -Encoding ascii

# 2. Compile the application modules to native code; then remove their sources.
Push-Location $Stage
try {
    foreach ($m in 'edition', 'licensing', 'dashboard') {
        Write-Host "Compiling $m to native code..."
        & $python -m nuitka --module "$m.py" --mingw64 --assume-yes-for-downloads --remove-output --quiet
        if ($LASTEXITCODE) { throw "Nuitka failed for $m" }
        Remove-Item "$m.py", "$m.pyi" -ErrorAction SilentlyContinue
    }
} finally { Pop-Location }
if (Get-ChildItem $Stage -Filter 'dashboard.py') { throw 'dashboard.py source must not be packaged' }

# 3. Package with PyInstaller.
$env:AI_CC_STAGE = $Stage; $env:AI_CC_SLUG = $Slug
Push-Location $Installer
try {
    & $python -m PyInstaller --clean --noconfirm --distpath dist --workpath build\pyi-onprem onprem.spec
    if ($LASTEXITCODE) { throw 'PyInstaller build failed' }
} finally { Pop-Location }
$leak = Get-ChildItem (Join-Path $Installer "dist\$Slug") -Recurse -Include 'dashboard.py', 'licensing.py', 'dashboard.pyc', 'licensing.pyc' -ErrorAction SilentlyContinue
if ($leak) { throw "Source/bytecode leaked into the package: $($leak.FullName -join ', ')" }

# 4. Installer.
$iscc = @("${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe", "$env:ProgramFiles\Inno Setup 6\ISCC.exe",
          "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $iscc) { throw 'Inno Setup 6 not found: winget install -e --id JRSoftware.InnoSetup' }
& $iscc "/DMyAppVersion=$($version.TrimStart('V'))" "/DMyAppName=$Name" "/DMyAppSlug=$Slug" "/DMyAppId=$AppId" (Join-Path $Installer 'installer.iss')
if ($LASTEXITCODE) { throw 'Installer build failed' }

# 5. USB package.
New-Item -ItemType Directory -Force $Usb | Out-Null
Copy-Item (Join-Path $Installer "output\$Slug-Setup-$($version.TrimStart('V')).exe") $Usb -Force
Copy-Item (Join-Path $Installer 'onprem-INSTALL.txt') (Join-Path $Usb 'INSTALL.txt') -Force
if (-not $SkipImages) {
    $env:AI_SECURITY_DATA = 'C:/unused'
    $images = docker compose -f (Join-Path $Edge 'runtime\docker-compose.yml') config --images
    Write-Host "Saving AI services for offline install: $($images -join ', ')"
    docker save -o (Join-Path $Usb 'ai-command-centre-images.tar') @images
    if ($LASTEXITCODE) { throw 'docker save failed (is Docker Desktop running with the images present?)' }
}
Get-ChildItem $Usb | Select-Object Name, @{n='MB';e={[math]::Round($_.Length/1MB,1)}} | Format-Table -AutoSize
Write-Host "On-prem package ready: $Usb" -ForegroundColor Green
